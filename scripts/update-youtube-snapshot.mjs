// Saves the channel's latest videos into src/content/youtubeSnapshot.ts.
// The site shows this list only when YouTube cannot be read from the server (it sometimes blocks
// cloud hosts). Run `node scripts/update-youtube-snapshot.mjs` on a normal connection, then commit.
import { writeFileSync } from "node:fs";

const channelId = "UCu7nmJaNLq1msJzRRzLBheQ";
const feeds = [
  `https://www.youtube.com/feeds/videos.xml?channel_id=${channelId}`,
  `https://www.youtube.com/feeds/videos.xml?playlist_id=UU${channelId.slice(2)}`,
];
const decode = (s) =>
  s.replace(/&amp;/g, "&").replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&quot;/g, '"').replace(/&#39;|&apos;/g, "'");

let videos = [];
for (let i = 0; i < 8 && videos.length === 0; i++) {
  try {
    const res = await fetch(`${feeds[i % 2]}&attempt=${i}`, { headers: { "User-Agent": "Mozilla/5.0" } });
    if (!res.ok) continue;
    videos = (await res.text())
      .split("<entry>")
      .slice(1)
      .map((e) => ({
        id: e.match(/<yt:videoId>([^<]+)</)?.[1],
        title: decode(e.match(/<title>([^<]*)</)?.[1] ?? ""),
        published: e.match(/<published>([^<]+)</)?.[1],
      }))
      .filter((v) => v.id && v.title && v.published)
      .sort((a, b) => b.published.localeCompare(a.published))
      .slice(0, 6);
  } catch {}
}
if (videos.length === 0) {
  console.error("YouTube could not be read; snapshot not changed.");
  process.exit(1);
}
const body = videos
  .map((v) => `  { id: ${JSON.stringify(v.id)}, title: ${JSON.stringify(v.title)}, published: ${JSON.stringify(v.published)} },`)
  .join("\n");
writeFileSync(
  new URL("../src/content/youtubeSnapshot.ts", import.meta.url),
  `/** Generated by scripts/update-youtube-snapshot.mjs. Used only when YouTube cannot be read live. */\nexport const youtubeSnapshot: { id: string; title: string; published: string }[] = [\n${body}\n];\n`,
);
console.log(`Saved ${videos.length} videos.`);
